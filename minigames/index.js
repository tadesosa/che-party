// Modos de los minijuegos que ya existían
const DEFAULT_MODES = {
  sumo: ['ffa', 'duel'], globo: ['ffa', 'duel'], alfajores: ['ffa', 'duel'], penales: ['ffa', 'duel'],
  carrera: ['ffa', 'duel'], sillas: ['ffa'], asado: ['ffa', 'duel'], cruce: ['ffa'], tango: ['ffa', 'duel'], pelota: ['ffa', 'duel'],
};
for (const [k, v] of Object.entries(LIST)) v.meta.modes = v.meta.modes || DEFAULT_MODES[k] || ['ffa'];

const MINIGAMES = Object.fromEntries(Object.entries(LIST).map(([k, v]) => [k, v.meta]));
function createMinigame(key, players, opts = {}) { return new LIST[key].Game(players, opts); }

module.exports = { MINIGAMES, createMinigame };
